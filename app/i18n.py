def clean_language(value):
    return value if value in LANGUAGES else DEFAULT_LANGUAGE


def request_language():
    """Limba cererii curente; în afara unei cereri (ex. workerul de emailuri), engleza."""
    if not has_request_context():
        return DEFAULT_LANGUAGE
    return request.accept_languages.best_match(LANGUAGES, default=DEFAULT_LANGUAGE)


def t(key, lang=None, **params):
    """Textul tradus; parametrul `field` e cheia unui câmp și se traduce și el."""
    messages = MESSAGES[clean_language(lang or request_language())]
    if 'field' in params:
        params['field'] = messages[f"field.{params['field']}"]
    return messages[key].format(**params)
